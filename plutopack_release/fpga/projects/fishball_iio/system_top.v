`timescale 1ns/100ps

module system_top (

  inout   [14:0]  ddr_addr,
  inout   [ 2:0]  ddr_ba,
  inout           ddr_cas_n,
  inout           ddr_ck_n,
  inout           ddr_ck_p,
  inout           ddr_cke,
  inout           ddr_cs_n,
  inout   [ 3:0]  ddr_dm,
  inout   [31:0]  ddr_dq,
  inout   [ 3:0]  ddr_dqs_n,
  inout   [ 3:0]  ddr_dqs_p,
  inout           ddr_odt,
  inout           ddr_ras_n,
  inout           ddr_reset_n,
  inout           ddr_we_n,

  inout           fixed_io_ddr_vrn,
  inout           fixed_io_ddr_vrp,
  inout   [53:0]  fixed_io_mio,
  inout           fixed_io_ps_clk,
  inout           fixed_io_ps_porb,
  inout           fixed_io_ps_srstb,

  inout           iic_scl,
  inout           iic_sda,

  input           rx_clk_in_p,
  input           rx_clk_in_n,
  input           rx_frame_in_p,
  input           rx_frame_in_n,
  input   [ 5:0]  rx_data_in_p,
  input   [ 5:0]  rx_data_in_n,
  output          tx_clk_out_p,
  output          tx_clk_out_n,
  output          tx_frame_out_p,
  output          tx_frame_out_n,
  output  [ 5:0]  tx_data_out_p,
  output  [ 5:0]  tx_data_out_n,

  output          enable,
  output          txnrx,

  inout           gpio_resetb,
  inout           gpio_en_agc,
  inout   [ 3:0]  gpio_ctl,
  inout   [ 7:0]  gpio_status,

  output          spi_csn,
  output          spi_clk,
  output          spi_mosi,
  input           spi_miso,

  output          pl_spi_clk_o,
  output          pl_spi_mosi,
  input           pl_spi_miso,

  // PlutoSky display (CH320QV15A-T, PS SPI1/EMIO) + MCU EMIO GPIO
  output          disp_sdi,    // SPI MOSI  -> display SDI
  input           disp_sdo,    // SPI MISO  <- display SDO
  output          disp_scl,    // SPI SCLK  -> display LCD_WR
  output          disp_csn,    // SPI CS    -> display LCD_RD
  output          disp_rs,     // D/C (GPIO)-> display LCD_RS (level-shifted 1.8V)
  inout   [ 6:0]  mcu_io       // MCU interface (EMIO GPIO)
);

  // internal signals

  wire    [17:0]  gpio_i;
  wire    [17:0]  gpio_o;
  wire    [17:0]  gpio_t;

  // display D/C (bit 0) + MCU (bits 7:1) EMIO GPIO breakout
  wire    [ 7:0]  disp_mcu_gpio_i;
  wire    [ 7:0]  disp_mcu_gpio_o;
  wire    [ 7:0]  disp_mcu_gpio_t;

  // instantiations

  // LCD_RS (D/C) is output-only; loop back its read value
  assign disp_rs = disp_mcu_gpio_o[0];
  assign disp_mcu_gpio_i[0] = disp_mcu_gpio_o[0];

  // MCU lines: 7 bidirectional EMIO GPIO
  ad_iobuf #(
    .DATA_WIDTH(7)
  ) i_mcu_iobuf (
    .dio_t (disp_mcu_gpio_t[7:1]),
    .dio_i (disp_mcu_gpio_o[7:1]),
    .dio_o (disp_mcu_gpio_i[7:1]),
    .dio_p (mcu_io));

  ad_iobuf #(
    .DATA_WIDTH(14)
  ) i_iobuf (
    .dio_t (gpio_t[13:0]),
    .dio_i (gpio_o[13:0]),
    .dio_o (gpio_i[13:0]),
    .dio_p ({ gpio_resetb,        // 13:13
              gpio_en_agc,        // 12:12
              gpio_ctl,           // 11: 8
              gpio_status}));     //  7: 0

  assign gpio_i[16:14] = gpio_o[16:14];



  system_wrapper i_system_wrapper (
    .ddr_addr (ddr_addr),
    .ddr_ba (ddr_ba),
    .ddr_cas_n (ddr_cas_n),
    .ddr_ck_n (ddr_ck_n),
    .ddr_ck_p (ddr_ck_p),
    .ddr_cke (ddr_cke),
    .ddr_cs_n (ddr_cs_n),
    .ddr_dm (ddr_dm),
    .ddr_dq (ddr_dq),
    .ddr_dqs_n (ddr_dqs_n),
    .ddr_dqs_p (ddr_dqs_p),
    .ddr_odt (ddr_odt),
    .ddr_ras_n (ddr_ras_n),
    .ddr_reset_n (ddr_reset_n),
    .ddr_we_n (ddr_we_n),
    .enable (enable),
    .fixed_io_ddr_vrn (fixed_io_ddr_vrn),
    .fixed_io_ddr_vrp (fixed_io_ddr_vrp),
    .fixed_io_mio (fixed_io_mio),
    .fixed_io_ps_clk (fixed_io_ps_clk),
    .fixed_io_ps_porb (fixed_io_ps_porb),
    .fixed_io_ps_srstb (fixed_io_ps_srstb),
    .gpio_i (gpio_i),
    .gpio_o (gpio_o),
    .gpio_t (gpio_t),
    .rx_clk_in_p (rx_clk_in_p),
    .rx_clk_in_n (rx_clk_in_n),
    .rx_data_in_p (rx_data_in_p),
    .rx_data_in_n (rx_data_in_n),
    .rx_frame_in_p (rx_frame_in_p),
    .rx_frame_in_n (rx_frame_in_n),

    .spi0_clk_i (1'b0),
    .spi0_clk_o (spi_clk),
    .spi0_csn_0_o (spi_csn),
    .spi0_csn_1_o (),
    .spi0_csn_2_o (),
    .spi0_csn_i (1'b1),
    .spi0_sdi_i (spi_miso),
    .spi0_sdo_i (1'b0),
    .spi0_sdo_o (spi_mosi),

    .spi1_clk_i (1'b0),
    .spi1_clk_o (disp_scl),
    .spi1_csn_0_o (disp_csn),
    .spi1_csn_i (1'b1),
    .spi1_sdi_i (disp_sdo),
    .spi1_sdo_i (1'b0),
    .spi1_sdo_o (disp_sdi),
    .disp_mcu_gpio_i (disp_mcu_gpio_i),
    .disp_mcu_gpio_o (disp_mcu_gpio_o),
    .disp_mcu_gpio_t (disp_mcu_gpio_t),


    .tx_clk_out_p (tx_clk_out_p),
    .tx_clk_out_n (tx_clk_out_n),
    .tx_data_out_p (tx_data_out_p),
    .tx_data_out_n (tx_data_out_n),
    .tx_frame_out_p (tx_frame_out_p),
    .tx_frame_out_n (tx_frame_out_n),
    .txnrx (txnrx),
    .up_enable (gpio_o[15]),
    .up_txnrx (gpio_o[16]));

endmodule
